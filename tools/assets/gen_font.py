def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    chars = list(GLYPHS.items())
    rows = (len(chars) + COLUMNS - 1) // COLUMNS
    sheet = Canvas(COLUMNS * CELL_W, rows * CELL_H)
    white = (255, 255, 255, 255)
    entries = []
    for i, (ch, glyph) in enumerate(chars):
        ox, oy = (i % COLUMNS) * CELL_W, (i // COLUMNS) * CELL_H
        sheet.from_ascii(glyph, {"#": white}, ox, oy)
        entries.append((ord(ch), ox, oy))
        if ch.isalpha() and ch.isupper() and ch.isascii():
            entries.append((ord(ch.lower()), ox, oy))
    sheet.save(os.path.join(OUT_DIR, "retroshift_5x7.png"))

    lines = [
        'info face="RetroShift 5x7" size=8 bold=0 italic=0 charset="" unicode=1 '
        "stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0",
        f"common lineHeight={CELL_H + 1} base=7 scaleW={sheet.width} scaleH={sheet.height} pages=1 packed=0",
        'page id=0 file="retroshift_5x7.png"',
        f"chars count={len(entries)}",
    ]
    for code, x, y in entries:
        lines.append(
            f"char id={code} x={x} y={y} width=5 height=7 xoffset=0 yoffset=0 xadvance={CELL_W} page=0 chnl=15"
        )
    with open(os.path.join(OUT_DIR, "retroshift_5x7.fnt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"font: {len(entries)} glyphs")


if __name__ == "__main__":
    main()
